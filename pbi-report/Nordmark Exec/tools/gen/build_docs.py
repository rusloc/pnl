def spec_ids(d):
    ids = sorted(set(re.findall(r"\b(?:E|ET)-\d+\b", d)), key=lambda x: (x[:2], int(x.split("-")[1])))
    return ", ".join(ids) or "–"


def cell(s):
    return s.replace("|", "\\|").replace("\n", " ")


def main():
    lines = [
        "# Nordmark Exec — measure dictionary",
        "",
        "> **DRAFT.** Model `pbi-report/Nordmark Exec/Nordmark Exec.SemanticModel`, table `_measures`. Generated by bip on 2026-10-28, regenerated",
        f"> 2026-10-30 for the period model of ADR-0013 (k) and the perf pass (SVG faces and pop-ups in one frame; {len(M)} measures). Governed by ADR-0013 (Accepted 2026-10-28); requirement IDs from",
        "> `docs/Requirements-exec.md`. Owner of every measure: bip. Tests: `pbi-report/Nordmark Exec/tests/control-totals.dax`",
        f"> ({TESTS}).",
        "",
        "## How the measures work",
        "",
        "- **Window = dim_week rows in context.** Every base measure (folders 1-7) evaluates over the weeks in its filter context and the",
        "  region picked in `param_region` (the leaf sums apply `dim_store[scope_code]`; ALL = no filter). The card layer (8) sets the window",
        "  from the picked item: `[_Item Key]` reads the three picker slicers (`param_granularity` type, `dim_item[fy_label]`, `dim_item[label]`",
        "  for Week / Month or `dim_item[label_wide]` for Quarter / Year) and falls back to the item of the picked type that holds the last pick",
        "  (Reset = Week 43 FY2026). `dim_item` (calculated from `dim_week`) carries every bound: `[_Window Start]` .. `[_Window End]`, the LY",
        "  window (`ly_week_key`, blank in FY2025), the previous item (`lw_week_key` at Week; else the item before, cut to the picked item's",
        "  weeks when it is partial) and the EBITDA Previous window at Week (previous month's first k weeks, blank for week 5 of a 5-week month).",
        "- **Flow vs point in time (E-93).** Flow metrics and channel mix sum over the window; stock, availability, GMROI and sell-through take",
        "  the window's last week. The EBITDA card reads `[EBITDA Flash]`: month to date when the window is one week (Week items), else the window.",
        "- **Status (E-22 .. E-26, E-95).** Badness per card in the rule unit, rounded to 10 decimals: On track if ≤ `watch_from`, Watch if ≤ `off_from`,",
        "  else Off track (`param_status_rule`); the Watch edge is Watch (data README open point 9). Status is always vs budget / target",
        "  (E-24), N/A where the value or its basis is blank (FY2025 has no budget); the dot uses the literal v5 rule over the cards with a",
        "  status, N/A excluded (none rated = grey), and follows the item and the region.",
        "- **Pickers.** `param_granularity` (filters `dim_item`), `param_comparator`, `param_region` (single select) and `param_attr_group / lever /",
        "  owner` (multi select) are disconnected from the facts. Attribute picks only conceal cards (`[Card Revealed <KPI>]`).",
        "- **Texts** follow `js-exec/lib/engine/format.ts` (minus U+2212, `€2,318m` from €1 bn up, `pp`, trimmed targets `97%`) and the",
        "  sentences of `view.ts`; copy comes from `js-exec/lib/engine/copy.ts` (shared copy source).",
        "- **SVG measures in one frame (perf pass 2026-10-30).** `Card SVG <KPI>`, `Info SVG <KPI>`, `Status Line SVG` and `Dot SVG` read the",
        "  slicers once (picked `dim_item` row, type, comparator, region, attribute state), then build the face inside one `CALCULATE` that clears",
        "  every picker table and passes the region as a `dim_store[scope_code]` filter, so the scoped leaf sums run their plain branch; every",
        "  window `CALCULATE` is one VAR. Value, comparator, status and texts are computed in place with the same DAX as the `Card ... <KPI>`",
        "  measures (which stay for the tests; T-N9 checks that both agree). A real dimension filter (e.g. `dim_category`) passes through.",
        "",
    ]
    for f in FOLDERS:
        ms = [m for m in M if m["folder"] == f]
        if not ms:
            continue
        lines += [f"## {f}", "", INTRO[f], "", "| Measure | Definition | Spec | Format | Hidden |", "|---|---|---|---|---|"]
        for m in ms:
            lines.append(f"| `{cell(m['name'])}` | {cell(m['desc'])} | {spec_ids(m['desc'])} | {cell(m['fmt'] or '–')} | {'yes' if m['hidden'] else ''} |")
        lines.append("")
        if f in ("8 Cards SVG",):
            continue
        lines += ["<details><summary>DAX</summary>", ""]
        for m in ms:
            lines += [f"**{m['name']}**", "", "```dax", f"{m['name']} =", m["expr"], "```", ""]
        lines += ["</details>", ""]
    write_lf(OUT, "\n".join(lines))
    print(f"dictionary: {len(M)} measures -> {OUT}")


if __name__ == "__main__":
    main()
